#!/usr/bin/env python3
"""Generates ios/Sources/ConjunctionCore/AppSupport/ConsentStrings.swift from legal/IN_APP_CONSENT_COPY.md.

The consent copy is shared word-for-word with Android (android/app/tools/import_consent_strings.py
writes consent_strings.xml from the same tables), and the consent record stores a hash of the text
shown, so the iOS strings are generated, never retyped. Rows look like  | `key` | Text |.
Keys become camelCase static lets on `L10n` (age_gate_title -> ageGateTitle); the Info.plist
usage strings (NS...) are generated too so a test can check project.yml carries them verbatim.
Placeholders keep the Android form (%1$s, %2$d, %%); `L10n.format` fills them.

    python3 -I ios/App/tools/import_consent_strings.py
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
IOS = HERE.parent.parent
SOURCE = IOS.parent / "legal" / "IN_APP_CONSENT_COPY.md"
TARGET = IOS / "Sources" / "ConjunctionCore" / "AppSupport" / "ConsentStrings.swift"
ROW = re.compile(r"^\|\s*`([A-Za-z0-9_]+)`(?:\s*\*\(store review\)\*)?\s*\|\s*(.+?)\s*\|\s*$")


def camel(key: str) -> str:
    if key.startswith("NS"):
        return "ns" + key[2:]
    head, *rest = key.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def swift_literal(text: str) -> str:
    # json.dumps gives a valid Swift string literal for BMP text once \u escapes are rewritten.
    s = json.dumps(text, ensure_ascii=False)
    s = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: "\\u{" + m.group(1) + "}", s)
    return s


def main() -> int:
    if not SOURCE.exists():
        print(f"missing {SOURCE}", file=sys.stderr)
        return 1
    version = "?"
    rows: list[tuple[str, str]] = []
    seen: set[str] = set()
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*Version\s*\|\s*(.+?)\s*\|", line)
        if m:
            version = m.group(1)
        m = ROW.match(line)
        if m and m.group(1) not in seen:
            seen.add(m.group(1))
            rows.append((m.group(1), m.group(2)))
    out = [
        "// GENERATED by ios/App/tools/import_consent_strings.py from legal/IN_APP_CONSENT_COPY.md",
        f"// (version {version}). Do not edit by hand; edit the markdown and re-run.",
        "// swiftlint:disable all",
        "import Foundation",
        "",
        "public enum L10n {",
        f"    public static let copyDocumentVersion = {swift_literal(version)}",
    ]
    for key, text in rows:
        out.append(f"    public static let {camel(key)} = {swift_literal(text)}")
    out.append("")
    out.append("    /// Every string by its markdown key (tests and the consent ledger).")
    out.append("    public static let all: [String: String] = [")
    for key, _ in rows:
        out.append(f"        {swift_literal(key)}: {camel(key)},")
    out.append("    ]")
    out.append("}")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} strings to {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
