package com.metavirtuoso.conjunction.core

import com.metavirtuoso.conjunction.core.astro.Angles
import com.metavirtuoso.conjunction.core.astro.HouseSystem
import com.metavirtuoso.conjunction.core.astro.Planet
import com.metavirtuoso.conjunction.core.astro.TimeScales
import com.metavirtuoso.conjunction.core.chart.BirthData
import com.metavirtuoso.conjunction.core.chart.NatalChart
import com.metavirtuoso.conjunction.core.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.Instant
import java.time.LocalDate
import java.time.LocalTime

/**
 * Checks the ephemeris against Swiss Ephemeris reference charts in testdata/golden_charts.json
 * (generated by testdata/tools/make_golden.py). Contract tolerances: planets 0.05 deg,
 * Ascendant / MC / Placidus cusps 0.1 deg.
 */
class GoldenChartTest {
    private val golden = TestData.json("golden_charts.json")
    private val charts = Json.arr(golden["charts"]).map(Json::obj)

    private fun birthOf(c: Map<String, Any?>) = BirthData(
        date = LocalDate.parse(c["date"] as String),
        time = (c["time"] as String?)?.let(LocalTime::parse),
        latitude = Json.num(c["latitude"]),
        longitude = Json.num(c["longitude"]),
        zoneId = c["zoneId"] as String,
        placeName = c["placeName"] as String,
    )

    @Test
    fun hasEnoughCharts() {
        assertTrue("need >= 40 golden charts", charts.size >= 40)
    }

    @Test
    fun timeZoneResolutionMatchesReference() {
        for (c in charts) {
            assertEquals(c["id"] as String, Instant.parse(c["utc"] as String), birthOf(c).instant)
        }
    }

    @Test
    fun deltaTMatchesSwissEphemeris() {
        for (c in charts) {
            val dt = TimeScales.deltaTSeconds(Instant.parse(c["utc"] as String))
            assertEquals(c["id"] as String, Json.num(c["deltaTSeconds"]), dt, 0.5)
        }
    }

    @Test
    fun planetsWithinFiveHundredthsOfADegree() {
        var worst = 0.0
        var worstLabel = ""
        for (c in charts) {
            val chart = NatalChart.compute(birthOf(c))
            val bodies = Json.obj(c["bodies"])
            for (planet in Planet.entries) {
                val ref = Json.obj(bodies[planet.key])
                val err = Angles.separation(chart.body(planet).longitude, Json.num(ref["longitude"]))
                if (err > worst) { worst = err; worstLabel = "${c["id"]} ${planet.key}" }
                assertTrue("${c["id"]} ${planet.key}: error ${"%.5f".format(err)} deg", err <= 0.05)
                val refSpeed = Json.num(ref["speed"])
                if (kotlin.math.abs(refSpeed) > 0.002) {
                    assertEquals("${c["id"]} ${planet.key} retrograde", ref["retrograde"] as Boolean, chart.body(planet).retrograde)
                }
            }
        }
        println("worst planet error: ${"%.5f".format(worst)} deg ($worstLabel)")
    }

    @Test
    fun anglesAndHouses() {
        var worst = 0.0
        for (c in charts) {
            val birth = birthOf(c)
            val whole = NatalChart.compute(birth)
            if (c["ascendant"] == null) {
                assertNull(whole.ascendant)
                assertNull(whole.houses)
                assertTrue(whole.bodies.all { it.house == null })
                continue
            }
            val ascErr = Angles.separation(assertNotNullAnd(whole.ascendant), Json.num(c["ascendant"]))
            val mcErr = Angles.separation(assertNotNullAnd(whole.midheaven), Json.num(c["midheaven"]))
            worst = maxOf(worst, ascErr, mcErr)
            assertTrue("${c["id"]} asc error $ascErr", ascErr <= 0.1)
            assertTrue("${c["id"]} mc error $mcErr", mcErr <= 0.1)
            val wsRef = Json.arr(c["wholeSignCusps"]).map(Json::num)
            assertEquals(wsRef, whole.houses)
            val placidusRef = c["placidusCusps"]
            val placidus = NatalChart.compute(birth, HouseSystem.PLACIDUS)
            if (placidusRef == null) {
                assertTrue("${c["id"]} should fall back to Porphyry", placidus.housesFellBack)
            } else {
                Json.arr(placidusRef).map(Json::num).forEachIndexed { i, ref ->
                    val err = Angles.separation(placidus.houses!![i], ref)
                    worst = maxOf(worst, err)
                    assertTrue("${c["id"]} Placidus cusp ${i + 1} error $err", err <= 0.1)
                }
            }
        }
        println("worst angle/cusp error: ${"%.5f".format(worst)} deg")
    }

    private fun assertNotNullAnd(v: Double?): Double { assertNotNull(v); return v!! }
}
