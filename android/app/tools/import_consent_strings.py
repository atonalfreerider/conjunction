#!/usr/bin/env python3
"""Generates res/values/consent_strings.xml from legal/IN_APP_CONSENT_COPY.md.

The consent copy is shared word-for-word with iOS, and the consent record stores a hash of the
text shown, so the Android strings are generated from the markdown tables instead of retyped.
Rows look like  | `key` | Text |.  iOS-only Info.plist keys (NS...) are skipped.

    python3 -I android/app/tools/import_consent_strings.py
"""
from __future__ import annotations

import pathlib
import re
import sys
from xml.sax.saxutils import escape

HERE = pathlib.Path(__file__).resolve().parent
APP = HERE.parent
SOURCE = APP.parent.parent / "legal" / "IN_APP_CONSENT_COPY.md"
TARGET = APP / "src" / "main" / "res" / "values" / "consent_strings.xml"
ROW = re.compile(r"^\|\s*`([a-z0-9_]+)`(?:\s*\*\(store review\)\*)?\s*\|\s*(.+?)\s*\|\s*$")


def android_escape(text: str) -> str:
    text = escape(text)
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def main() -> int:
    if not SOURCE.exists():
        print(f"missing {SOURCE}", file=sys.stderr)
        return 1
    version = "?"
    rows: list[tuple[str, str]] = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*Version\s*\|\s*(.+?)\s*\|", line)
        if m:
            version = m.group(1)
        m = ROW.match(line)
        if m and not m.group(1).startswith("NS"):
            rows.append((m.group(1), m.group(2)))
    seen: set[str] = set()
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- GENERATED by android/app/tools/import_consent_strings.py from legal/IN_APP_CONSENT_COPY.md",
        f"     (version {escape(version)}). Do not edit by hand; edit the markdown and re-run. -->",
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,Typos">',
    ]
    for key, text in rows:
        if key in seen:
            continue
        seen.add(key)
        formatted = "%" in text and re.search(r"%\d\$[sd]", text) is not None
        attr = "" if formatted else ' formatted="false"'
        out.append(f'    <string name="{key}"{attr}>{android_escape(text)}</string>')
    out.append("</resources>")
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(seen)} strings to {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
